def sources_page(catalog, registry, docs):
    source_ids = {s["id"] for s in registry}
    entries = Counter(p["source"] for e in catalog["engines"] for p in e["provenance"])
    families = Counter(s for e in catalog["engines"] for s in {p["source"] for p in e["provenance"]})
    collected = {s["id"]: s for s in catalog.get("sources", [])}
    contents = "".join(f'<li><a href="#{text(s["id"])}">{text(s["name"])}</a></li>' for s in registry)
    body = (
        f"<p>All {len(registry)} engine lists used as provenance for the catalog, followed by the "
        '<a href="#methodology">collection and research methodology</a>. Being listed is provenance, '
        "not an independent guarantee of source-code availability.</p>"
        f'<nav aria-label="Lists on this page"><ol class="toc">{contents}</ol></nav>'
    )
    for source in registry:
        observed = collected.get(source["id"], {})
        warnings = observed.get("warnings", [])
        pairs = [
            ("List URL", link(source["url"])),
            ("Description", text(DESCRIPTIONS.get(source["collector"], "Registered engine list."))),
            ("Coverage", f"{families[source['id']]:,} families from {entries[source['id']]:,} list entries"),
            ("Collection status", text(observed["status"]) if observed.get("status") else None),
            ("Collected", text(observed["checked_at"]) if observed.get("checked_at") else None),
            ("Collector", link(f"{REPOSITORY_FILES}collectors/{source['collector']}.py",
                               f"collectors/{source['collector']}.py")),
            ("Collection warnings", "<ul>" + "".join(f"<li>{text(w)}</li>" for w in warnings) + "</ul>"
             if warnings else None),
        ]
        for key in ("members", "bot_accounts", "non_bot_accounts_excluded", "resolved_accounts", "unresolved_accounts"):
            if key in observed:
                pairs.append((key.replace("_", " ").capitalize(), text(observed[key])))
        notes = md_blocks(doc_after(docs.get(source["id"], ""), "How it was found"), "docs/sources", source_ids)
        body += section(source["name"], definition_list(pairs) + notes, source["id"])

    candidates = md_blocks(doc_after(docs.get("README", ""), "OpenBench candidates"), "docs/sources", source_ids)
    methodology = f"""
<h3>Collection</h3>
<p>Each registered list has its own parser. Collectors fetch public pages through a shared cache, spacing every
request at least 1.1 seconds apart and backing off on HTTP 429. Observed labels, list URLs, ranks, authors and
collection timestamps are preserved as provenance. A failed refresh keeps the previous observations.</p>
<h3>Engine families</h3>
<p>Versions and builds collapse into families. Names are deduplicated case-insensitively, with reviewed aliases
for spelling differences. Forks, ports and derivatives stay separate, and same-named programs by different
authors are split using source-scoped rules backed by author evidence. Lichess accounts are attributed only
by reviewed profile evidence or an unambiguous name match.</p>
<h3>Source code and research</h3>
<p>Source-code links come from explicit repository or source links on the lists, reviewed Chess Programming
Wiki links, and separate web research for families without such links. Research records two independent
axes—availability and licensing—with confidence, release scope, rationale, quotations and evidence URLs.
Source from a precursor, successor or homonym is never attributed. “Source available” includes archived-only
copies; “Source not located” never implies closed-source. Links are not audited for safety or completeness and
may refer to older releases than those currently listed.</p>
<h3>Publishing</h3>
<p>This site is generated by <code>publish.py</code> from the repository's local catalog and research records,
without network access; the collection date is not a new link-check date. Full details are in the
{link(REPOSITORY + "#readme", "repository README")}.</p>
"""
    methodology += section("Availability", definition_list(
        [(AVAILABILITY[k], text(v)) for k, v in AVAILABILITY_DETAIL.items() if k != "not_checked"]), level=3)
    methodology += section("Licensing", definition_list(
        [(LICENSING[k], text(v)) for k, v in source_status.LICENSING.items()]), level=3)
    methodology += section("Research confidence", definition_list(
        [(CONFIDENCE[k], text(v)) for k, v in source_status.CONFIDENCE.items()]), level=3)
    methodology += section("Research tiers", definition_list(
        [(k, text(v)) for k, v in source_status.TIERS.items()]), level=3)
    methodology += section("Research rules", "<ul>" + "".join(
        f"<li>{text(rule)}</li>" for rule in source_status.RULES) + "</ul>", level=3)
    if candidates:
        methodology += candidates
    body += section("Methodology and limitations", methodology, "methodology")
    return page("Sources and methodology", body, generated_at=catalog.get("generated_at"))


# ---------------------------------------------------------------- build

def build(catalog, status, registry, overrides, wiki_reviews, docs, out):
    if not catalog.get("engines"):
        raise ValueError("catalog has no engine families")
    out = Path(out).resolve()
    if out == ROOT or out in ROOT.parents:
        raise ValueError("output must not be the repository root or one of its parents")
    # Work on a copy so attaching research never changes the caller's catalog.
    catalog = json.loads(json.dumps(catalog))
    catalog["engines"].sort(key=lambda e: source_status.name_sort_key(e["name"]))
    source_status.attach(catalog, status)
    slugs = source_status.family_slugs(catalog["engines"])
    if len(slugs) != len(catalog["engines"]):
        raise ValueError("catalog contains duplicate family names")
    registry_by_id = {s["id"]: s for s in registry}
    unknown = {p["source"] for e in catalog["engines"] for p in e["provenance"]} - set(registry_by_id)
    if unknown:
        raise ValueError(f"provenance sources missing from sources.json: {', '.join(sorted(unknown))}")
    registry_by_id["source-status-research"] = {"name": "Source-status research"}

    for directory in ("families", "assets", "downloads"):
        (out / directory).mkdir(parents=True, exist_ok=True)
    generated_at = catalog.get("generated_at", "")
    (out / "index.html").write_text(index_page(catalog, overrides, slugs), encoding="utf-8")
    (out / "sources.html").write_text(sources_page(catalog, registry, docs), encoding="utf-8")
    written = set()
    similar = similar_names(catalog["engines"])
    author_of = {e["name"]: "; ".join(value for value, _ in authors(e)) for e in catalog["engines"]}
    for rule in overrides.get("related_families", []):
        for name in (rule["family"], rule["related"]):
            if name not in slugs:
                print(f"WARNING: related_families names unknown family {name!r}; review overrides.json")
    for engine in catalog["engines"]:
        name = engine["name"]
        html = family_page(engine, status.get("families", {}).get(name, {}), registry_by_id,
                           overrides, slugs, wiki_reviews.get(name, {}), generated_at, similar, author_of)
        filename = slugs[name] + ".html"
        (out / "families" / filename).write_text(html, encoding="utf-8")
        written.add(filename)
    for stale in (out / "families").glob("*.html"):
        if stale.name not in written and GENERATED in stale.read_text(encoding="utf-8")[:200]:
            stale.unlink()
    for asset in ASSETS:
        shutil.copyfile(ROOT / "site_assets" / asset, out / "assets" / asset)

    downloads = out / "downloads"
    for retired in ("engines.json", "source-status.json"):
        # Earlier versions copied the JSON data into the site; it is now linked from the repository.
        (downloads / retired).unlink(missing_ok=True)
    (downloads / "engines.csv").write_text(collect.catalog_csv(catalog["engines"]), encoding="utf-8", newline="")
    rows, count = names_pdf.entries(catalog)
    if not count:
        raise ValueError("no source-available families for the printable PDF")
    portrait = names_pdf.PAPER["poster"]
    page_size = (portrait[1], portrait[0])
    try:
        size, _ = names_pdf.choose(rows, page_size, 16, 1)
    except SystemExit as error:
        raise ValueError(f"printable PDF: {error}") from None
    pages = names_pdf.render(
        rows, count, size, page_size, downloads / "source-available-engines.pdf",
        names_pdf.source_links(catalog),
    )
    return len(catalog["engines"]), pages, size


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def read_docs(directory):
    return {path.stem: path.read_text(encoding="utf-8") for path in Path(directory).glob("*.md")}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=ROOT / "dist", help="output directory (default: dist)")
    args = parser.parse_args()
    try:
        count, pages, size = build(
            read_json(ROOT / "data" / "engines.json"),
            read_json(ROOT / "data" / "source-status.json"),
            read_json(ROOT / "sources.json"),
            read_json(ROOT / "overrides.json"),
            read_json(ROOT / "wiki-source-overrides.json"),
            read_docs(ROOT / "docs" / "sources"),
            args.out,
        )
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"publish failed: {error}\n"
                       "Run `python collect.py --offline` first if data/engines.json is missing.\n")
    print(f"Wrote {count:,} family pages, index, sources, assets and downloads to {args.out}")
    print(f"Printable PDF: {pages} pages at {size:g} pt")


if __name__ == "__main__":
    main()
