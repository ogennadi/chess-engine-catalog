    name = engine["name"]
    state = availability(engine)
    aliases = all_aliases(engine, overrides)
    licences = research_licences(record)
    questions = open_questions(engine, record)
    decisions = reviewed_decisions(engine, record, overrides, slugs, wiki_review)
    if questions:
        review = f'<span class="tag tag-open">{len(questions)} open question{"s" * (len(questions) != 1)}</span>'
    elif record:
        review = '<span class="tag">No open questions recorded</span>'
    else:
        review = "Not separately researched"

    if record:
        licensing = (
            f"{text(LICENSING[record['licensing']])} "
            f'<span class="muted">({text(source_status.LICENSING[record["licensing"]])})</span>'
        )
        confidence = (
            f"{text(CONFIDENCE[record['confidence']])} "
            f'<span class="muted">({text(source_status.CONFIDENCE[record["confidence"]])})</span>'
        )
    else:
        licensing = "Not separately researched; check the licence in the linked source."
        confidence = None
    body = '<p><a href="../index.html">← All engine families</a></p>'
    body += definition_list([
        ("Author", author_html(engine, registry)),
        ("Also credited", text("; ".join(also_credited(engine))) + ' <span class="muted">(listed in parentheses '
         "by RWBC)</span>" if also_credited(engine) else None),
        ("Source availability", f'<strong>{text(AVAILABILITY[state])}</strong> '
                                f'<span class="muted">({text(AVAILABILITY_DETAIL[state])})</span>'),
        ("Licensing assessment", licensing),
        ("Research confidence", confidence),
        ("Research tier", text(f"{record['tier']}: {source_status.TIERS.get(record['tier'], '')}")
         if record.get("tier") else None),
        ("Researched", text(record["checked_at"]) if record.get("checked_at") else None),
        ("Review status", review),
    ])
    body += ('<p class="muted">Availability and licensing are assessed separately. '
             "“Source not located” does not mean closed-source, and available source does not by itself "
             "grant permission to reuse it.</p>")

    body += section("Known names", (
        "<ul>" + "".join(f"<li>{text(a)}</li>" for a in aliases) + "</ul>"
        if aliases else "<p>No other names recorded.</p>"
    ), "names")
    body += related_section(engine, overrides, slugs, similar or {}, author_of or {})

    codes = engine.get("source_code", [])
    if codes:
        items = []
        for code in codes:
            research = licences.get(code["url"].rstrip("/").casefold(), {})
            pairs = [
                ("Kind", text(code.get("kind") or research.get("kind") or "")),
                ("Licence", text(research["license"]) if research.get("license") else None),
                ("Release scope", text(code["source_release"]) if code.get("source_release") else None),
                ("Note", text(code["note"]) if code.get("note") else None),
                ("Evidence", link(code["evidence_url"]) if code.get("evidence_url") else None),
                ("Recorded by", text(registry.get(code.get("source"), {}).get("name", code.get("source", "")))),
                ("Checked", text(code["checked_at"]) if code.get("checked_at") else None),
            ]
            items.append(f"<li>{link(code['url'])}{definition_list(pairs, 'metadata')}</li>")
        caveat = ""
        if state not in AVAILABLE:
            caveat = ('<p class="notice">Research did not confirm that these collected references contain this '
                      "engine's source; see the research findings below.</p>")
        body += section("Source code", caveat + "<ul>" + "".join(items) + "</ul>", "source-code")
    else:
        body += section("Source code", "<p>No source-code copy was located in the collected lists or research. "
                                       "This does not mean the engine is closed-source.</p>", "source-code")

    wiki = engine.get("chessprogramming_wiki", {})
    wiki_status = wiki.get("status", "not_checked")
    if wiki.get("url"):
        wiki_html = f"<p>{link(wiki['url'], wiki.get('title') or wiki['url'])}</p>"
    elif wiki_status == "not_found":
        checked = ", ".join(wiki.get("titles_checked", [])) or name
        wiki_html = f"<p>No matching page was found under the checked names: {text(checked)}.</p>"
    elif wiki_status == "needs_review":
        wiki_html = "<p>A similarly named page exists but its identity is unconfirmed, so it is not linked.</p>"
    else:
        wiki_html = "<p>Not checked yet.</p>"
    if wiki.get("checked_at"):
        wiki_html += f'<p class="muted">Checked {text(wiki["checked_at"])}.</p>'
    body += section("Chess Programming Wiki", wiki_html, "wiki")

    if record:
        findings = definition_list([
            ("Rationale", text(record.get("rationale", ""))),
            ("Release scope", text(record["release_scope"]) if record.get("release_scope") else None),
            ("Notes", text(record["notes"]) if record.get("notes") and record.get("needs_review") is not False else None),
            ("Searches recorded", text(record["searches"]) if record.get("searches") else None),
        ])
        evidence = record.get("evidence", [])
        findings += f"<h3>Evidence ({len(evidence)})</h3>"
        findings += "<ol class=\"evidence\">" + "".join(evidence_item(e) for e in evidence) + "</ol>"
        body += section("Research findings", findings, "research")

    body += section("Open questions", (
        '<ul class="open-questions">' + "".join(f"<li>{text(q)}</li>" for q in questions) + "</ul>"
        if questions else "<p>None recorded.</p>"
    ), "open-questions")
    body += section("Reviewed decisions", (
        '<ul class="decisions">' + "".join(f"<li>{d}</li>" for d in decisions) + "</ul>"
        if decisions else "<p>No family-specific identity or licence decisions recorded.</p>"
    ), "decisions")

    provenance = []
    for source_id in sorted({p["source"] for p in engine["provenance"]},
                            key=lambda s: registry.get(s, {}).get("name", s).casefold()):
        source = registry.get(source_id, {"name": source_id, "url": ""})
        observations = [p for p in engine["provenance"] if p["source"] == source_id]
        entries = "".join(provenance_entry(p) for p in observations)
        plural = "entry" if len(observations) == 1 else "entries"
        provenance.append(
            f'<li><a href="../sources.html#{text(source_id)}">{text(source["name"])}</a>'
            + (f' — {link(source["url"], "original list")}' if source.get("url") else "")
            + f"<details><summary>{len(observations):,} list {plural}</summary><ul>{entries}</ul></details></li>"
        )
    body += section("Provenance lists", '<ul class="provenance">' + "".join(provenance) + "</ul>", "provenance")
    return page(name, body, "../", generated_at, f"{name}: aliases, source code and research evidence.")


