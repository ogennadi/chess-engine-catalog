# Reviewed relation -> (label on the family's page, label on the related family's page).
RELATIONS = {
    "derived_from": ("Derived from", "Has derivative"),
    "successor_of": ("Successor of", "Succeeded by"),
    "same_name": ("Same name, different program", "Same name, different program"),
    "distinct_from": ("Not to be confused with", "Not to be confused with"),
}


def base_name(name):
    """Name without a trailing qualifier, so "Atlas (1967)" groups with "Atlas"."""
    return collect.identity_key(re.sub(r"\s*\([^()]*\)$", "", name)) or collect.identity_key(name)


def similar_names(engines):
    groups = {}
    for engine in engines:
        groups.setdefault(base_name(engine["name"]), []).append(engine["name"])
    return groups


def related_families(engine, overrides, similar):
    """Reviewed relationships in both directions, then unreviewed families sharing the base name."""
    name = engine["name"]
    reviewed = []
    for rule in overrides.get("related_families", []):
        forward, backward = RELATIONS[rule["relation"]]
        if name == rule["family"]:
            reviewed.append((forward, rule["related"], rule.get("note", ""), rule.get("evidence_url")))
        elif name == rule["related"]:
            reviewed.append((backward, rule["family"], rule.get("note", ""), rule.get("evidence_url")))
    for rule in overrides.get("source_aliases", []):
        if name in (rule.get("family"), rule.get("target")) and rule["family"] != rule["target"]:
            other = rule["target"] if name == rule["family"] else rule["family"]
            reviewed.append((RELATIONS["same_name"][0], other, rule.get("note", ""), rule.get("evidence_url")))
    unique, seen = [], set()
    for item in reviewed:
        if (item[0], item[1]) not in seen:
            seen.add((item[0], item[1]))
            unique.append(item)
    known = {other for _, other, _, _ in unique}
    unreviewed = [other for other in similar.get(base_name(name), []) if other != name and other not in known]
    return unique, sorted(unreviewed, key=lambda name: (name.casefold(), name))


def related_section(engine, overrides, slugs, similar, author_of):
    reviewed, unreviewed = related_families(engine, overrides, similar)
    if not reviewed and not unreviewed:
        return ""

    def family_link(other):
        html = f'<a href="{slugs[other]}.html">{text(other)}</a>' if other in slugs else text(other)
        if author_of.get(other):
            html += f' <span class="muted">by {text(author_of[other])}</span>'
        return html

    body = ""
    if reviewed:
        body += "<ul>" + "".join(
            f"<li><strong>{text(label)}:</strong> {family_link(other)}. {text(note)}"
            f"{' ' + link(evidence, 'Evidence') if evidence else ''}</li>"
            for label, other, note, evidence in reviewed
        ) + "</ul>"
    if unreviewed:
        body += ('<p>Families with a similar name, <strong>not reviewed</strong> as related; '
                 "listed to help tell them apart:</p><ul>"
                 + "".join(f"<li>{family_link(other)}</li>" for other in unreviewed) + "</ul>")
    return section("Related families", body, "related")


def name_words(name):
    folded = unicodedata.normalize("NFKD", name.casefold())
    return frozenset(re.findall(r"\w+", "".join(c for c in folded if not unicodedata.combining(c)))) - {"and"}


def authors(engine):
    """Author names recorded by the lists, as (name, [source ids]); duplicates in other word orders are merged."""
    found = []
    # Natural-order sources first: RWBC writes "Surname Given", which would otherwise be shown.
    for source in ("wiki-engines", "computer-chess-org", "lucas-chess", "rwbc", "amateurschach"):
        # Frank's author column has ditto marks and typos, so it only fills gaps.
        if source == "amateurschach" and found:
            break
        for item in engine.get("provenance", []):
            if item.get("source") != source:
                continue
            if source == "wiki-engines":
                prefix = f"{item.get('listed_name', '')} by "
                names = [item["label"][len(prefix):]] if item.get("label", "").startswith(prefix) else []
            elif source == "rwbc":
                names = str(item.get("authors") or "").splitlines()
            elif source == "amateurschach":
                names = list(item.get("authors") or [])
            else:
                names = [item.get("author") or ""]
            for value in names:
                value = value.strip().strip("*").strip()
                words = name_words(value)
                # RWBC parenthesises some names, e.g. "(Ablett Jim)"; they are shown separately by also_credited().
                if not words or value in ("-", "?") or value.startswith("("):
                    continue
                for entry in found:
                    if words <= entry[2]:
                        if source not in entry[1]:
                            entry[1].append(source)
                        break
                else:
                    absorbed = [i for i, entry in enumerate(found) if entry[2] <= words]
                    sources = list(dict.fromkeys([s for i in absorbed for s in found[i][1]] + [source]))
                    at = absorbed[0] if absorbed else len(found)
                    found = [entry for i, entry in enumerate(found) if i not in absorbed]
                    found.insert(at, (value, sources, words))
    return [(value, sources) for value, sources, _ in found]


def also_credited(engine):
    names = []
    for item in engine.get("provenance", []):
        if item.get("source") == "rwbc":
            for line in str(item.get("authors") or "").splitlines():
                line = line.strip().strip("*").strip()
                if line.startswith("(") and line.endswith(")") and line[1:-1].strip() not in names:
                    names.append(line[1:-1].strip())
    return names


def author_html(engine, registry):
    items = [
        f"{text(value)} <span class=\"muted\">({text(', '.join(registry.get(s, {}).get('name', s) for s in sources))})</span>"
        for value, sources in authors(engine)
    ]
    return "; ".join(items) if items else '<span class="muted">Not recorded by the collected lists</span>'


def research_licences(record):
    return {item["url"].rstrip("/").casefold(): item for item in record.get("source_urls", [])}


def source_cell(engine):
    state = availability(engine)
    if state not in AVAILABLE:
        return f'<span class="status">{text(AVAILABILITY[state])}</span>'
    urls = list(dict.fromkeys(item["url"] for item in engine["source_code"]))
    if not urls:
        raise ValueError(f"{engine['name']}: {state} source has no links")
    seen = Counter()
    links = []
    for url in urls:
        name = host(url)
        seen[name] += 1
        label = name if seen[name] == 1 else f"{name} ({seen[name]})"
        links.append(f"<li>{link(url, label)}</li>")
    tag = '<span class="tag">Archived only</span>' if state == "archived_only" else ""
    return f'{tag}<ul class="source-links">{"".join(links)}</ul>'


def open_questions(engine, record):
    """Unresolved research questions, kept separate from reviewed decisions."""
    questions = []
    if record.get("needs_review"):
        questions.append("This research record is flagged for further review.")
    if unresolved_text(record.get("identity_issue")) and record.get("needs_review") is not False:
        questions.append("Identity: " + record["identity_issue"])
    if record.get("licensing") == "unknown":
        questions.append("Licensing is unknown: no rights-holder licence or closed-source statement was found.")
    state = availability(engine)
    if state == "released_not_located":
        questions.append("Source was reportedly released, but no copy has been located.")
    elif state == "not_checked":
        questions.append("Source availability has not been researched yet.")
    if state in AVAILABLE:
        for item in record.get("source_urls", []):
            licence = item.get("license")
            if not licence or UNCLEAR_LICENCE.search(licence):
                questions.append(
                    f"Licence for {item['url']} is not clearly established"
                    + (f" (recorded: {licence})." if licence else ".")
                )
    wiki_status = engine.get("chessprogramming_wiki", {}).get("status", "not_checked")
    if wiki_status == "needs_review":
        questions.append("A Chess Programming Wiki page with a similar name needs identity review; it is not linked.")
    elif wiki_status == "not_checked":
        questions.append("The Chess Programming Wiki has not been checked for this family yet.")
    return questions


def reviewed_decisions(engine, record, overrides, slugs, wiki_review):
    """Reviewed identity, alias and source-link decisions (HTML items)."""
    decisions = []
    if record.get("needs_review") is False:
        detail = []
        if unresolved_text(record.get("identity_issue")):
            detail.append("Question considered: " + record["identity_issue"])
        if record.get("notes"):
            detail.append("Decision: " + record["notes"])
        decisions.append("Research record reviewed. " + text(" ".join(detail)))
    if unresolved_text(record.get("identity_note")):
        decisions.append("Identity: " + text(record["identity_note"]))
    for rule in overrides.get("source_aliases", []):
        if engine["name"] not in (rule.get("family"), rule.get("target")):
            continue
        other = rule["target"] if rule.get("family") == engine["name"] else rule["family"]
        other_html = f'<a href="{slugs[other]}.html">{text(other)}</a>' if other in slugs else text(other)
        sources = ", ".join(rule.get("sources", []))
        decisions.append(
            f"Same-name split between {text(rule['family'])} and {text(rule['target'])} "
            f"(related family: {other_html}; applies to: {text(sources or 'all sources')}). "
            f"{text(rule.get('note', ''))} {link(rule['evidence_url'], 'Identity evidence')}"
            if rule.get("evidence_url") else
            f"Same-name split; related family: {other_html}. {text(rule.get('note', ''))}"
        )
    merged = sorted(
        (alias for alias, target in overrides.get("aliases", {}).items() if target == engine["name"]),
        key=str.casefold,
    )
    if merged:
        decisions.append("Reviewed aliases merged into this family: " + text(", ".join(merged)) + ".")
    for item in engine.get("provenance", []):
        if item.get("identity_note") or item.get("identity_evidence_url"):
            evidence = item.get("identity_evidence_url")
            decisions.append(
                f"Listing “{text(item['label'])}” attributed to this family. {text(item.get('identity_note', ''))} "
                + (link(evidence, "Evidence") if evidence else "")
            )
    for code in engine.get("rejected_source_code", []):
        decisions.append(
            f"Not counted as source code: {link(code['url'])} (listed by {text(code['source'])}). "
            f"{text(code['reason'])} {link(code['review_evidence_url'], 'Evidence')}"
        )
    wiki = engine.get("chessprogramming_wiki", {})
    if wiki.get("method", "").startswith("reviewed"):
        decisions.append(f"Chess Programming Wiki page “{text(wiki.get('title', ''))}” matched by a reviewed mapping.")
    if wiki_review:
        urls = "".join(
            f"<li>{link(code['url'])}{(' — ' + text(code['note'])) if code.get('note') else ''}</li>"
            for code in wiki_review.get("code_urls", [])
        )
        decisions.append(
            "Wiki source-link review: " + text(wiki_review.get("note", ""))
            + (f"<ul>{urls}</ul>" if urls else " No wiki-linked URL was accepted as this engine's source.")
        )
    return list(dict.fromkeys(decisions))


def evidence_item(item):
    parts = []
    if item.get("quote"):
        parts.append(f"<blockquote>{text(item['quote'])}</blockquote>")
    where = []
    if item.get("url"):
        where.append(link(item["url"]))
    if item.get("search"):
        where.append(f"Search: <q>{text(item['search'])}</q>")
    if item.get("source"):
        where.append(f"Source: {text(item['source'])}")
    if item.get("user_input"):
        where.append(f"Repository owner: <q>{text(item['user_input'])}</q>")
    if item.get("notes"):
        where.append(text(item["notes"]))
    if where:
        parts.append('<p class="evidence-source">' + " · ".join(where) + "</p>")
    return "<li>" + "".join(parts) + "</li>"


def provenance_entry(item):
    pairs = []
    for key, name in PROVENANCE_URLS:
        if item.get(key):
            pairs.append((name, link(item[key])))
    for url in item.get("links", []) or []:
        pairs.append(("Linked from entry", link(url)))
    for key, name in PROVENANCE_FIELDS:
        value = item.get(key)
        if value not in (None, "", "-", []):
            pairs.append((name, text(", ".join(map(str, value)) if isinstance(value, list) else value)))
    return f"<li><strong>{text(item['label'])}</strong>{definition_list(pairs, 'metadata')}</li>"


