def resolve_doc_link(url, base, source_ids):
    if is_web_url(url):
        return url
    if url.startswith("#") or urlsplit(url).scheme:
        return None
    path = posixpath.normpath(posixpath.join(base, url))
    if path.startswith(".."):
        return None
    name = posixpath.basename(path)
    if posixpath.dirname(path) == "docs/sources" and name.endswith(".md") and name[:-3] in source_ids:
        return "#" + name[:-3]
    return REPOSITORY_FILES + path


def md_inline(source, base, source_ids):
    pattern = re.compile(r"`([^`]+)`|\[((?:`[^`]*`|[^\]])+)\]\(([^)\s]+)\)|<(https?://[^>\s]+)>|\*\*(.+?)\*\*")
    out, position = [], 0
    for match in pattern.finditer(source):
        out.append(text(source[position:match.start()]))
        code, label, url, autolink, bold = match.groups()
        if code is not None:
            out.append(f"<code>{text(code)}</code>")
        elif label is not None:
            target = resolve_doc_link(url, base, source_ids)
            inner = md_inline(label, base, source_ids)
            out.append(anchor(target, inner) if target else inner)
        elif autolink is not None:
            out.append(link(autolink))
        else:
            out.append(f"<strong>{md_inline(bold, base, source_ids)}</strong>")
        position = match.end()
    out.append(text(source[position:]))
    return "".join(out)


def md_blocks(markdown, base, source_ids, heading_level=3):
    """Render the small Markdown subset used in docs/sources: headings, paragraphs, lists and tables."""
    html, paragraph, items, rows = [], [], [], []

    def flush():
        if paragraph:
            html.append(f"<p>{md_inline(' '.join(paragraph), base, source_ids)}</p>")
            paragraph.clear()
        if items:
            html.append("<ul>" + "".join(f"<li>{md_inline(i, base, source_ids)}</li>" for i in items) + "</ul>")
            items.clear()
        if rows:
            head, *body = rows
            html.append(
                '<div class="table-wrap"><table class="doc-table"><thead><tr>'
                + "".join(f'<th scope="col">{md_inline(c, base, source_ids)}</th>' for c in head)
                + "</tr></thead><tbody>"
                + "".join("<tr>" + "".join(f"<td>{md_inline(c, base, source_ids)}</td>" for c in row) + "</tr>"
                          for row in body)
                + "</tbody></table></div>"
            )
            rows.clear()

    for line in markdown.splitlines():
        stripped = line.strip()
        heading = re.match(r"(#+)\s+(.*)", stripped)
        if not stripped:
            flush()
        elif heading:
            flush()
            level = min(6, heading_level + len(heading.group(1)) - 2)
            html.append(f"<h{level}>{md_inline(heading.group(2), base, source_ids)}</h{level}>")
        elif stripped.startswith("|"):
            if paragraph or items:
                flush()
            cells = [c.strip() for c in re.split(r"(?<!\\)\|", stripped.strip("|"))]
            if not all(re.fullmatch(r":?-+:?", c) for c in cells):
                rows.append([c.replace("\\|", "|") for c in cells])
        elif re.match(r"[-*]\s+", stripped):
            if paragraph or rows:
                flush()
            items.append(re.sub(r"^[-*]\s+", "", stripped))
        elif items and line[:1].isspace():
            items[-1] += " " + stripped
        else:
            if items or rows:
                flush()
            paragraph.append(stripped)
    flush()
    return "".join(html)


def doc_after(markdown, heading):
    """Return the Markdown from the first heading matching `heading` to the end."""
    match = re.search(rf"^#+\s+{heading}", markdown, re.M)
    return markdown[match.start():] if match else ""


