def all_aliases(engine, overrides):
    names = set(engine.get("aliases", []))
    names.update(alias for alias, target in overrides.get("aliases", {}).items() if target == engine["name"])
    for item in engine.get("provenance", []):
        # RWBC alternate names also hold parenthesised ancestry notes such as "(Pesto PST)"; those are not names.
        for alternate in str(item.get("alternate_names") or "").splitlines():
            alternate = alternate.strip()
            if alternate and alternate != "-" and not alternate.startswith("("):
                names.add(alternate)
    names.discard(engine["name"])
    return sorted(names, key=lambda name: (name.casefold(), name))


